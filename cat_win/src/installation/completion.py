"""
completion
"""

import os
import sys

from cat_win.src.const.argconstants import ALL_ARGS, VALUE_DESCRIPTIONS
from cat_win.src.service.helper.environment import on_windows_os
from cat_win.src.service.helper.iohelper import logger


# shells we can emit completions for
SUPPORTED_SHELLS = ('bash', 'fish', 'zsh')

# basename of the two console scripts, both get the same completions
CONSOLE_SCRIPTS = ('catw', 'cats')


def detect_shell() -> str:
    """
    guess the currently running shell from the environment.

    Returns:
    (str):
        one of SUPPORTED_SHELLS
    """
    # prefer an explicit indication over the process name, since a completion
    # script is usually sourced rather than executed
    for env_var, shell in (
        ('ZSH_VERSION', 'zsh'),
        ('BASH_VERSION', 'bash'),
        ('FISH_VERSION', 'fish')
    ):
        if env_var in os.environ:
            return shell
    base = os.path.basename(sys.argv[0] or '').lower()
    for shell in SUPPORTED_SHELLS:
        if base.startswith(shell):
            return shell
    # not running under a shell we know (a service, a script, `python -m`),
    # so fall back to the user's configured login shell
    configured = os.path.basename(os.environ.get('SHELL', '') or '').lower()
    if configured in SUPPORTED_SHELLS:
        return configured
    return SUPPORTED_SHELLS[0]


def generate_bash() -> str:
    """
    Build a bash completion script.

    Returns:
    (str):
        the completion script
    """
    lines = '# bash completion for cat_win\n' \
            '# generated by "catw --generate-completion=bash"; do not edit by hand.\n\n' \
            '_cat_win_completion() {\n' \
            '    local cur prev opts opt val full\n' \
            '    COMPREPLY=()\n' \
            '    cur="${COMP_WORDS[COMP_CWORD]}"\n' \
            '    prev=""\n' \
            '    if (( COMP_CWORD > 0 )); then\n' \
            '        prev="${COMP_WORDS[COMP_CWORD-1]}"\n' \
            '    fi\n' \
            '    opts="'

    for arg in ALL_ARGS:
        for form in (arg.short_form, arg.long_form):
            if not form:
                continue
            if arg.arg_id < 0 and arg.metavar:
                continue
            lines += f"{form} "

    lines += '"\n\n'

    # options with a fixed set of values, e.g. '--generate-completion=zsh'
    value_options = []
    for arg in ALL_ARGS:
        if not arg.takes_value:
            continue
        values = ' '.join(VALUE_DESCRIPTIONS[arg.takes_value][1])
        for form in (arg.short_form, arg.long_form):
            if form and form.startswith('-') and (form, values) not in value_options:
                value_options.append((form, values))

    if value_options:
        lines += '    opt=""\n' \
                 '    val="$cur"\n' \
                 '    full=0\n' \
                 '    if [[ "$cur" == "=" ]]; then\n' \
                 '        opt="$prev"\n' \
                 '        val=""\n' \
                 '    elif [[ "$prev" == "=" ]]; then\n' \
                 '        opt="${COMP_WORDS[COMP_CWORD-2]}"\n' \
                 '    elif [[ "$cur" == *=* ]]; then\n' \
                 '        opt="${cur%%=*}"\n' \
                 '        val="${cur#*=}"\n' \
                 '        full=1\n' \
                 '    fi\n' \
                 '    case "$opt" in\n'
        for form, values in value_options:
            lines += f'            {form})\n' \
                     f'                COMPREPLY=( $(compgen -W "{values}" -- "$val") )\n' \
                     '                if (( full )); then\n' \
                     f'                    COMPREPLY=( "${{COMPREPLY[@]/#/{form}=}}" )\n' \
                     '                fi\n' \
                     '                return 0\n' \
                     '                ;;\n'
        lines += '        esac\n'

    lines += '\n' \
             '    case "$cur" in\n' \
             '        -*)\n' \
             '            COMPREPLY=( $(compgen -W "$opts" -- "$cur") )\n'

    if value_options:
        choices = '|'.join(form for form, _ in value_options)
        lines += '            if [[ ${#COMPREPLY[@]} -eq 1 ]]; then\n' \
                 '                case "${COMPREPLY[0]}" in\n' \
                 f'                    {choices})\n' \
                 '                        if command -v compopt >/dev/null 2>&1; then\n' \
                 '                            COMPREPLY=( "${COMPREPLY[0]}=" )\n' \
                 '                            compopt -o nospace\n' \
                 '                        fi\n' \
                 '                        ;;\n' \
                 '                esac\n' \
                 '            fi\n'

    lines += '            ;;\n' \
             '        *)\n' \
             '            # default to file completion; cat_win takes FILEs as operands\n' \
             '            COMPREPLY=( $(compgen -f -- "$cur") )\n' \
             '            ;;\n' \
             '    esac\n' \
             '    return 0\n' \
             '}\n\n' \
             'complete -F _cat_win_completion catw\n' \
             'complete -F _cat_win_completion cats\n'

    return lines


def generate_zsh() -> str:
    """
    Build a zsh completion script.

    Returns:
    (str):
        the completion script
    """
    lines = '#compdef catw cats\n' \
            '# zsh completion for cat_win\n' \
            '# generated by "catw --generate-completion=zsh"; do not edit by hand.\n\n' \
            '_cat_win_completion() {\n' \
            '    local -a args\n' \
            '    args=(\n'

    # operand-style forms ('find=X', 'fg', ...) are not options: _arguments
    # only accepts them as a normal-argument spec, and only one of those may
    # appear, so every operand form is merged into the single spec below
    operands = []
    for arg in ALL_ARGS:
        for form in (arg.short_form, arg.long_form):
            if not form:
                continue
            if not form.startswith('-'):
                if form not in operands:
                    operands.append(form)
                continue
            if arg.arg_id < 0 and arg.metavar or '[' in form:
                continue
            if arg.takes_value:
                value_help, values = VALUE_DESCRIPTIONS[arg.takes_value]
                lines += f"        '{form}=-[{arg.arg_help}]:{value_help}:({' '.join(values)})'\n"
            else:
                lines += f"        '{form}[{arg.arg_help}]'\n"

    if operands:
        message = ', '.join(form for form in operands if ':' not in form)
        words = ' '.join(operands)
        lines += f"        '*:{message}:({words})'\n"

    lines += '    )\n\n' \
             '    _arguments -s -S : $args\n' \
             '    _files\n' \
             '    (( compstate[nmatches] ))\n' \
             '}\n\n' \
             '_cat_win_completion "$@"\n'

    return lines


def generate_fish() -> str:
    """
    Build a fish completion script.
    https://fishshell.com/docs/current/completions.html

    Returns:
    (str):
        the completion script
    """
    lines = '# fish completion for cat_win\n' \
            '# generated by "catw --generate-completion=fish"; do not edit by hand.\n\n'

    for script in CONSOLE_SCRIPTS:
        for arg in ALL_ARGS:
            if arg.arg_id < 0 and arg.metavar:
                continue

            line = f"complete -c {script}"

            for form in (arg.short_form, arg.long_form):
                if not form:
                    continue
                if form.startswith('--') and len(form) > 2:
                    line += f" -l '{form[2:]}'"
                elif form.startswith('-') and len(form) == 2:
                    line += f" -s '{form[1:]}'"
            line += f" -d '{arg.arg_help}'"

            if arg.takes_value:
                line += f" --no-files -a \"{' '.join(VALUE_DESCRIPTIONS[arg.takes_value][1])}\""

            lines += line + '\n'

    return lines


GENERATORS = {
    'bash': generate_bash,
    'fish': generate_fish,
    'zsh' : generate_zsh,
}
def build_completion(shell: str) -> str:
    """
    generate a completion script for a specific shell.

    Parameters:
    shell (str):
        one of SUPPORTED_SHELLS

    Returns:
    (str):
        the completion script
    """
    generator = GENERATORS.get(shell)
    if generator is None:
        raise SystemExit(3)
    return generator()


# where each shell expects a completion script to live
COMPLETION_PATHS = {
    'bash': '.local/share/bash-completion/completions/catw',
    'fish': '.config/fish/completions/catw.fish',
    'zsh' : '.local/share/zsh/site-functions/_catw',
}
def completion_path(shell: str) -> str:
    """
    where a shell expects its completion script.

    Parameters:
    shell (str):
        the shell name

    Returns:
    (str):
        the file path
    """
    relative = COMPLETION_PATHS.get(shell)
    if relative is None:
        raise SystemExit(2)
    return os.path.join(os.path.expanduser('~'), relative)


def install_hint(shell: str) -> str:
    """
    explain how to install the completion script for a specific shell.

    Parameters:
    shell (str):
        the shell to give completion instructions for

    Returns:
    (str):
        a block of ready-to-run commands
    """
    target = completion_path(shell)
    target_dir = os.path.dirname(target)
    install = f"to install the completion script for {shell}, run:\n" \
              f"  mkdir -p {target_dir}\n" \
              f"  catw --generate-completion={shell} 2>/dev/null > {target}\n"
    if shell == 'zsh':
        install += f"  # zsh needs the directory on $fpath in ~/.zshrc:\n"
        install += f"  #   fpath=(\"{target_dir}\" $fpath)\n\n"
    install += f"to remove it again, run:\n" \
               f"  rm -f {target}\n"

    return install


def show_completion(shell: str = None) -> int:
    """
    print the completion script to stdout and its install commands to stderr.

    Parameters:
    shell (str):
        the shell to generate completion for; detected when None

    Returns:
    (int):
        process exit code -- 0 on success, > 0 on failure
    """
    if on_windows_os:
        logger(
            'sudo is a unix feature; nothing to do on windows.',
            priority=logger.INFO
        )
        return 0

    shell = (shell or detect_shell()).lower()

    if shell is not None and shell not in SUPPORTED_SHELLS:
        logger(f"unknown shell: {shell}", priority=logger.ERROR)
        logger(
            'expected one of: ' + ', '.join(SUPPORTED_SHELLS),
            priority=logger.ERROR
        )
        return 1

    # stdout carries only the script, so it can be piped into the
    # install command without the instructions ending up in the file
    print(build_completion(shell), end='')
    logger(install_hint(shell), priority=logger.INFO)
    return 0
