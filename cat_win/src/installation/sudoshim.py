"""
sudoshim
"""

from cat_win.src.service.helper.environment import on_windows_os
from cat_win.src.service.helper.iohelper import logger


# where a system wide binary belongs, i.e. the directory sudo does search
SHIM_DIR = '/usr/local/bin'

# the names this shim is meant to be installed under
CONSOLE_SCRIPTS = ('catw', 'cats')

# searched by the shim at runtime, relative to the invoking user's home
# must not contain the shim's own directory or it would exec itself
_USER_BIN_DIRS = ('.local/bin', 'bin')

# the shim is root-owned and must not be writable by anyone else
_SHIM_MODE = '755'

_SHIM_TEMPLATE = """#!/bin/sh
# sudo shim for cat_win -- generated by "catw --generate-sudoshim".
# Do not edit by hand; regenerate it instead.
#
# sudo resets HOME to root's, so this delegates to the *invoking* User's own
# installation and pins the Config Directory to that User. Without the pin,
# `sudo catw` would silently use root's Config instead of the caller's.

# Dispatch on the Name this was invoked as, so the same File works whether it
# is installed as catw or as cats.
_cw_script=$(basename "$0")

_cw_user="${{SUDO_USER:-${{USER:-root}}}}"
_cw_home=$(getent passwd "$_cw_user" 2>/dev/null | cut -d: -f6)
[ -n "$_cw_home" ] || _cw_home="${{HOME:-/root}}"

# An explicit override always wins.
if [ -z "${{CAT_WIN_CONFIG_DIR:-}}" ]; then
    CAT_WIN_CONFIG_DIR="$_cw_home/.config"
    export CAT_WIN_CONFIG_DIR
fi

# This script's own directory is intentionally absent from the search list:
# it would make the shim exec itself forever.
for _cw_dir in {candidates}; do
    if [ -x "$_cw_dir/$_cw_script" ] && [ ! -d "$_cw_dir/$_cw_script" ]; then
        exec "$_cw_dir/$_cw_script" "$@"
    fi
done

echo "$_cw_script: no installation found for user '$_cw_user' (home '$_cw_home')" >&2
exit 127
"""


def build_shim() -> str:
    """
    render the sudo shim.

    the script carries no hardcoded script name, so the same file works
    installed as `catw` or as `cats`.
    it reads $0 to serve both entry points.

    Returns:
    (str):
        the full shell script
    """
    candidates = ' '.join('"$_cw_home/' + sub + '"' for sub in _USER_BIN_DIRS)
    return _SHIM_TEMPLATE.format(candidates=candidates)


def install_hint(script: str = None) -> str:
    """
    explain how to install the generated shim.

    the commands use `tee` plus `chmod` rather than a single `install`
    because `/dev/stdin` is not portable across coreutils and BSD, and they
    are written out in full so it is obvious what touches a privileged location.

    Parameters:
    script (str):
        restrict the commands to this one console script.
        both are covered when None

    Returns:
    (str):
        a block of ready-to-run commands
    """
    names = (script,) if script else CONSOLE_SCRIPTS
    targets = ' '.join(SHIM_DIR + '/' + name for name in names)

    if script:
        install = f"  catw --generate-sudoshim={script} | sudo tee {SHIM_DIR}/{script} > /dev/null\n" \
                  f"  sudo chmod {_SHIM_MODE} {SHIM_DIR}/{script}"
    else:
        install = f"  for n in {' '.join(CONSOLE_SCRIPTS)}; do \\\n" \
                  f"    catw --generate-sudoshim | sudo tee {SHIM_DIR}/$n > /dev/null\n" \
                  f"    sudo chmod {_SHIM_MODE} {SHIM_DIR}/$n\n" \
                  f"  done"

    return f"sudo shim for cat_win -- generated by 'catw --generate-sudoshim'.\n" \
           f"Do not edit by hand; regenerate it instead.\n\n" \
           f"to install the shim, run:\n{install}" + '\n\n' \
           f"to remove it again, run:\n" \
           f"  sudo rm -f {targets}\n\n" \
           f"verify with:\n" \
           f"  sudo {names[0]} --version\n"


def show_shim(script: str = None) -> int:
    """
    print the shim to stdout and its install commands to stderr.

    Parameters:
    script (str):
        the console script the Commands should cover; both when None

    Returns:
    (int):
        process exit code -- 0 on success, 1 on failure
    """
    if on_windows_os:
        logger(
            'sudo is a unix feature; nothing to do on windows.',
            priority=logger.INFO
        )
        return 0

    if script is not None and script not in CONSOLE_SCRIPTS:
        logger(f"unknown script: {script}", priority=logger.ERROR)
        logger(
            'expected one of: ' + ', '.join(CONSOLE_SCRIPTS),
            priority=logger.ERROR
        )
        return 1

    # stdout carries only the script, so it can be piped into the
    # install command without the instructions ending up in the file
    print(build_shim(), end='')
    logger(install_hint(script), priority=logger.INFO)
    return 0
